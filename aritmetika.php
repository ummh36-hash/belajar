<?php

$angka1 = 10;
$angka2 = 5;

// + Penjumlahan
echo "hasil penjumlahan: " , ($angka1 + $angka2); //hasilnya 15

// - pengurangan
echo "<br>"; 
echo "hasil pengurangan: " , ($angka1 - $angka2); //hasilnya 5

// * perkalian
echo "<br>";
echo "hasil perkalian: " , ($angka1 * $angka2); //hasilnya 50

// pembagian
echo "<br>";
echo "hasil pembagian: " , ($angka1 / $angka2); //hasilnya 2

// % modulus
echo "<br>";
echo "hasil modulus: " , ($angka1 % $angka2); //hasilnya 0
?>